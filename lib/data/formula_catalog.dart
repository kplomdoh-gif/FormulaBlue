Formula _buildFormula(String subject, _Seed seed) {
  final (name, expression, note, example, symbols, difficulty) = seed;
  final meanings = _variableMeanings[subject]!;
  final variables = symbols
      .split(',')
      .map((symbol) {
        final meaning =
            meanings[symbol] ?? 'the $symbol quantity in this equation';
        return '$symbol: $meaning';
      })
      .toList(growable: false);
  final icon = switch (subject) {
    'Mathematics' || 'Algebra' => Icons.functions_rounded,
    'Geometry' => Icons.change_history_rounded,
    'Physics' => Icons.bolt_rounded,
    'Chemistry' => Icons.science_rounded,
    _ => Icons.account_balance_rounded,
  };
  return Formula(
    name: name,
    subject: subject,
    expression: expression,
    note: note,
    icon: icon,
    explanation:
        '$note Substitute the known values, keep units consistent, and rearrange to find the unknown.',
    variables: variables,
    example: example,
    difficulty: difficulty,
  );
}

